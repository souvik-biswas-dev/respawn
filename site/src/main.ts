const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);
const dur = (s: number) => (s < 120 ? `${s} s` : `${Math.floor(s / 60)} min ${s % 60} s`);
const utc = (iso: string) => iso.replace("T", " ").replace(":00Z", "Z").replace(/:\d\dZ$/, "Z");
const clock = (iso: string, plus: number) => new Date(Date.parse(iso) + plus * 1000).toISOString().slice(11, 19) + "Z";

function headline(d: Data): string {
  const r = d.runs.find((x) => x.drill === "delete-server") ?? d.runs[d.runs.length - 1];
  const lost = Math.max(0, r.last_seq_before - r.first_seq_after);
  const sim = r.mode === "simulated";
  const verb = r.drill === "delete-server" ? (sim ? "A simulated server deletion" : "The server was deleted") : `The ${r.drill} drill`;
  return `<h1>${verb} was recovered in <span class="big">${dur(r.rto_seconds)}</span>.</h1>
  <p class="loss">${lost ? `${lost.toLocaleString("en")} canary rows were lost, about ${dur(r.rpo_seconds)} of writes.` : "No canary rows were lost."}</p>
  <p class="sub">${sim ? "These figures were generated by <code>--simulate</code>. Nothing was broken and nothing was measured." : "Measured on real infrastructure with <code>make drill-all</code>."}</p>`;
}

function traceBlock(r: Run): string {
  const lost = Math.max(0, r.last_seq_before - r.first_seq_after);
  const tags = r.alerts_fired.length
    ? r.alerts_fired.map((a) => `<li class="tag${r.mode === "simulated" ? " exp" : ""}">${esc(a)}</li>`).join("")
    : `<li class="none">none recorded</li>`;
  return `<section class="rec" id="${r.drill}" aria-labelledby="h-${r.drill}">
  <div class="meta">
    <h2 id="h-${r.drill}">${r.drill}</h2>
    <p class="rto"><span class="n">${dur(r.rto_seconds)}</span><span class="u">to recover</span></p>
    <p class="m">${lost ? `${lost.toLocaleString("en")} rows lost` : "0 rows lost"}</p>
    <p class="m">${r.mode === "simulated" ? '<b class="simtag">SIMULATED</b>' : "<b>real run</b>"}</p>
  </div>
  <div class="plot">
    <div class="scroll" tabindex="0" role="group" aria-label="${r.drill} trace, scrollable"><div class="wide">${traceSvg(r)}${stripSvg(r)}</div></div>
    <p class="hint">swipe sideways to see the whole trace</p>
    <ul class="tags" aria-label="Alerts that fired">${tags}</ul>
    ${r.mode === "simulated" && r.alerts_fired.length ? `<p class="note">Dashed tags are the alerts expected for this drill, not observed.</p>` : ""}
    ${r.notes ? `<p class="note">${esc(r.notes)}</p>` : ""}
  </div>
</section>`;
}

function ledger(r?: Run): string {
  if (!r) return "";
  let t = 0;
  const rows = r.steps.map((s) => { const row = `<tr><td>${clock(r.fault_injected_at, t)}</td><td>${esc(s.name)}</td><td class="num">${s.seconds} s</td></tr>`; t += s.seconds; return row; });
  const rest = r.rto_seconds - t;
  if (rest > 2) rows.push(`<tr><td>${clock(r.fault_injected_at, t)}</td><td>polling and waiting between steps</td><td class="num">${rest} s</td></tr>`);
  return `<section class="ledger" aria-labelledby="h-ledger"><h2 id="h-ledger">Rebuild ledger: delete-server</h2>
  <p class="m">Fault injected at ${clock(r.fault_injected_at, 0)}. Each row starts when the previous one ended.</p>
  <table><thead><tr><th scope="col">clock (UTC)</th><th scope="col">step</th><th scope="col" class="num">took</th></tr></thead><tbody>${rows.join("")}
  <tr class="total"><td>${clock(r.fault_injected_at, r.rto_seconds)}</td><td>health check passes, timer stops</td><td class="num">${r.rto_seconds} s</td></tr></tbody></table></section>`;
}

const CMDS = [
  ["see this page with fake data", "make drill-simulate"],
  ["run all three drills for real", 'make drill-all DRILL_ARGS="--host respawn-1 --via local --age-key keys.txt --yes-really"'],
  ["rebuild this page from the results", "make site-build"],
];

function render(d: Data) {
  const latest = d.runs.map((r) => r.recovered_at).sort().pop()!;
  const mode = d.simulated ? "simulated" : "real";
  const banner = d.simulated
    ? `<div class="banner" role="status"><b>SIMULATED DATA</b> ${d.index.source === "sample" ? "Committed samples, not measured." : "At least one run below was simulated."} The README table only takes numbers from real runs.</div>` : "";
  document.getElementById("app")!.innerHTML = `${banner}
  <header class="recbar"><span class="dot" aria-hidden="true"></span><span>REC</span><span>latest run ${utc(latest)}</span><span>mode ${mode}</span><span>source ${d.index.source}</span></header>
  <main>
    <div class="top">${headline(d)}</div>
    ${d.runs.map(traceBlock).join("")}
    ${ledger(d.runs.find((r) => r.drill === "delete-server"))}
    <section class="repro" aria-labelledby="h-repro"><h2 id="h-repro">Reproduce it</h2>
      ${CMDS.map(([l, c]) => `<div class="cmd"><p class="m">${l}</p><pre><code>${esc(c)}</code></pre><button type="button" data-copy="${esc(c)}">copy</button></div>`).join("")}
    </section>
  </main>
  <footer><p class="m">Respawn Console. Built from drills/results at ${utc(d.index.generated_at.slice(0, 19) + "Z")}. A single node means a node loss is an outage until rebuilt; these drills measure how long.</p></footer>`;
  document.querySelectorAll<HTMLButtonElement>("button[data-copy]").forEach((b) => b.addEventListener("click", async () => {
    try { await navigator.clipboard.writeText(b.dataset.copy!); b.textContent = "copied"; } catch { b.textContent = "select and copy"; }
    setTimeout(() => (b.textContent = "copy"), 1800);
  }));
  if (!matchMedia("(prefers-reduced-motion: reduce)").matches) replay();
}

// Scrolling replays each recording: pre-fault line, the fault, the flatline, then recovery.
function replay() {
  gsap.registerPlugin(ScrollTrigger);
  document.querySelectorAll<SVGSVGElement>("svg.trace").forEach((svg) => {
    const p = (ph: string) => svg.querySelector<SVGPathElement>(`path[data-ph="${ph}"]`)!;
    const tl = gsap.timeline({ scrollTrigger: { trigger: svg, start: "top 88%", end: "bottom 50%", scrub: 0.6 } });
    const marks = (ph: string) => Array.from(svg.querySelectorAll(`.mk[data-ph="${ph}"]`));
    gsap.set(svg.querySelectorAll(".mk"), { opacity: 0 });
    [["pre", 3], ["spike", 0.8], ["flat", 4], ["post", 2.2]].forEach(([ph, d]) => {
      const el = p(ph as string), len = el.getTotalLength();
      gsap.set(el, { strokeDasharray: len, strokeDashoffset: len });
      tl.to(el, { strokeDashoffset: 0, duration: d as number, ease: "none" });
      if (ph === "spike") tl.to(marks("fault"), { opacity: 1, duration: 0.2 }, "<");
      if (ph === "flat") tl.to(marks("flat"), { opacity: 1, duration: 0.3 }, "<0.3");
      if (ph === "flat") tl.to(marks("rec"), { opacity: 1, duration: 0.3 });
    });
  });
}

load().then(render).catch(() => {
  document.getElementById("app")!.innerHTML = `<main><h1>No recording found.</h1><p class="sub">Run <code>make drill-simulate</code> or <code>make drill-all</code>, then <code>make site-build</code>.</p></main>`;
});
